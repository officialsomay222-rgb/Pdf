    /**
     * Saves all extracted image files to the user's phone Gallery, returning count saved.
     */
    fun saveAllImagesToGallery(
        context: Context,
        files: List<File>,
        baseTitle: String
    ): Int {
        var count = 0
        for ((idx, file) in files.withIndex()) {
            val uri = saveImageFileToGallery(
                context = context,
                sourceFile = file,
                title = "${baseTitle}_page_${idx + 1}"
            )
            if (uri != null) count++
        }
        return count
    }

