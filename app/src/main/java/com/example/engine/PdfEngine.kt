package com.example.engine

import android.content.Context
import android.graphics.*
import android.graphics.pdf.PdfDocument
import com.example.model.*
import java.io.File
import java.io.FileOutputStream
import java.text.SimpleDateFormat
import java.util.*

object PdfEngine {

    /**
     * Generates a real, standardized PDF file from the document workspace
     * including vector blueprints, annotations, measurements, stamps, and signatures.
     */
    fun exportToPdfFile(
        context: Context,
        documentTitle: String,
        pageCount: Int,
        category: DocumentCategory,
        annotations: List<AnnotationItem>,
        measurements: List<MeasurementItem>,
        formFields: List<FormFieldItem>,
        watermark: String = ""
    ): File {
        val pdfDocument = PdfDocument()
        val pageWidth = 792 // Standard US Letter Landscape or A4 points
        val pageHeight = 612

        val titlePaint = Paint().apply {
            color = Color.DKGRAY
            textSize = 14f
            isAntiAlias = true
            typeface = Typeface.create(Typeface.DEFAULT, Typeface.BOLD)
        }

        val textPaint = Paint().apply {
            color = Color.BLACK
            textSize = 10f
            isAntiAlias = true
        }

        val watermarkPaint = Paint().apply {
            color = Color.argb(45, 220, 38, 38) // Translucent red
            textSize = 32f
            isAntiAlias = true
            typeface = Typeface.create(Typeface.DEFAULT, Typeface.BOLD)
            textAlign = Paint.Align.CENTER
        }

        for (pageIndex in 0 until pageCount) {
            val pageInfo = PdfDocument.PageInfo.Builder(pageWidth, pageHeight, pageIndex + 1).create()
            val page = pdfDocument.startPage(pageInfo)
            val canvas = page.canvas

            // 1. Draw Page Background
            val bgPaint = Paint().apply {
                color = when (category) {
                    DocumentCategory.BLUEPRINT -> Color.rgb(240, 244, 250) // Technical light blueprint tint
                    else -> Color.WHITE
                }
            }
            canvas.drawRect(0f, 0f, pageWidth.toFloat(), pageHeight.toFloat(), bgPaint)

            // 2. Draw Blueprint Grid if Blueprint category
            if (category == DocumentCategory.BLUEPRINT) {
                val gridPaint = Paint().apply {
                    color = Color.rgb(215, 225, 240)
                    strokeWidth = 0.5f
                }
                for (x in 20 until pageWidth step 20) {
                    canvas.drawLine(x.toFloat(), 40f, x.toFloat(), (pageHeight - 40).toFloat(), gridPaint)
                }
                for (y in 40 until pageHeight - 40 step 20) {
                    canvas.drawLine(20f, y.toFloat(), (pageWidth - 20).toFloat(), y.toFloat(), gridPaint)
                }
            }

            // 3. Draw Document Header & Border
            val borderPaint = Paint().apply {
                color = Color.rgb(150, 160, 180)
                strokeWidth = 1.5f
                style = Paint.Style.STROKE
            }
            canvas.drawRect(20f, 20f, (pageWidth - 20).toFloat(), (pageHeight - 20).toFloat(), borderPaint)

            // Header banner
            canvas.drawText("$documentTitle | Page ${pageIndex + 1} of $pageCount", 30f, 36f, titlePaint)
            val dateStr = SimpleDateFormat("yyyy-MM-dd HH:mm", Locale.US).format(Date())
            canvas.drawText("Generated by Document OS Enterprise Engine • $dateStr", 30f, (pageHeight - 26).toFloat(), textPaint)

            // 4. Draw Watermark if present
            if (watermark.isNotBlank()) {
                canvas.save()
                canvas.rotate(-30f, (pageWidth / 2).toFloat(), (pageHeight / 2).toFloat())
                canvas.drawText(watermark, (pageWidth / 2).toFloat(), (pageHeight / 2).toFloat(), watermarkPaint)
                canvas.restore()
            }

            // 5. Draw Annotations on this page
            val pageAnnotations = annotations.filter { it.pageIndex == pageIndex }
            for (ann in pageAnnotations) {
                val p = Paint().apply {
                    color = ann.colorHex.toInt()
                    strokeWidth = ann.strokeWidth
                    isAntiAlias = true
                    alpha = (ann.opacity * 255).toInt()
                }

                when (ann.type) {
                    MarkupType.PEN -> {
                        if (ann.points.size > 1) {
                            p.style = Paint.Style.STROKE
                            p.strokeCap = Paint.Cap.ROUND
                            p.strokeJoin = Paint.Join.ROUND
                            val path = Path()
                            path.moveTo(ann.points[0].x, ann.points[0].y)
                            for (i in 1 until ann.points.size) {
                                path.lineTo(ann.points[i].x, ann.points[i].y)
                            }
                            canvas.drawPath(path, p)
                        }
                    }
                    MarkupType.HIGHLIGHTER -> {
                        if (ann.points.size >= 2) {
                            p.style = Paint.Style.FILL
                            p.alpha = 90
                            val left = minOf(ann.points[0].x, ann.points[1].x)
                            val top = minOf(ann.points[0].y, ann.points[1].y)
                            val right = maxOf(ann.points[0].x, ann.points[1].x)
                            val bottom = maxOf(ann.points[0].y, ann.points[1].y)
                            canvas.drawRect(left, top, right, bottom, p)
                        }
                    }
                    MarkupType.RECTANGLE -> {
                        if (ann.points.size >= 2) {
                            p.style = Paint.Style.STROKE
                            val left = minOf(ann.points[0].x, ann.points[1].x)
                            val top = minOf(ann.points[0].y, ann.points[1].y)
                            val right = maxOf(ann.points[0].x, ann.points[1].x)
                            val bottom = maxOf(ann.points[0].y, ann.points[1].y)
                            canvas.drawRect(left, top, right, bottom, p)
                        }
                    }
                    MarkupType.REVISION_CLOUD -> {
                        if (ann.points.size >= 2) {
                            p.style = Paint.Style.STROKE
                            p.strokeWidth = 2.5f
                            val left = minOf(ann.points[0].x, ann.points[1].x)
                            val top = minOf(ann.points[0].y, ann.points[1].y)
                            val right = maxOf(ann.points[0].x, ann.points[1].x)
                            val bottom = maxOf(ann.points[0].y, ann.points[1].y)
                            val rect = RectF(left, top, right, bottom)
                            canvas.drawRoundRect(rect, 12f, 12f, p)
                        }
                    }
                    MarkupType.CALLOUT, MarkupType.TEXT_NOTE -> {
                        if (ann.points.isNotEmpty()) {
                            val pt = ann.points[0]
                            val notePaint = Paint().apply {
                                color = Color.BLACK
                                textSize = ann.fontSize
                                isAntiAlias = true
                            }
                            canvas.drawText(ann.text, pt.x, pt.y, notePaint)
                        }
                    }
                    MarkupType.REDACTION_BOX -> {
                        if (ann.points.size >= 2) {
                            val rPaint = Paint().apply {
                                color = Color.BLACK
                                style = Paint.Style.FILL
                            }
                            val left = minOf(ann.points[0].x, ann.points[1].x)
                            val top = minOf(ann.points[0].y, ann.points[1].y)
                            val right = maxOf(ann.points[0].x, ann.points[1].x)
                            val bottom = maxOf(ann.points[0].y, ann.points[1].y)
                            canvas.drawRect(left, top, right, bottom, rPaint)
                        }
                    }
                    MarkupType.STAMP -> {
                        if (ann.points.isNotEmpty() && ann.stampType != null) {
                            val pt = ann.points[0]
                            val sPaint = Paint().apply {
                                color = ann.stampType.colorHex.toInt()
                                style = Paint.Style.STROKE
                                strokeWidth = 2.5f
                                isAntiAlias = true
                            }
                            val sTextPaint = Paint().apply {
                                color = ann.stampType.colorHex.toInt()
                                textSize = 13f
                                typeface = Typeface.create(Typeface.DEFAULT, Typeface.BOLD)
                                isAntiAlias = true
                            }
                            val stampRect = RectF(pt.x, pt.y, pt.x + 160f, pt.y + 40f)
                            canvas.drawRoundRect(stampRect, 6f, 6f, sPaint)
                            canvas.drawText(ann.stampType.label, pt.x + 12f, pt.y + 26f, sTextPaint)
                        }
                    }
                    else -> {}
                }
            }

            // 6. Draw Measurements
            val pageMeasurements = measurements.filter { it.pageIndex == pageIndex }
            for (meas in pageMeasurements) {
                val mPaint = Paint().apply {
                    color = meas.colorHex.toInt()
                    strokeWidth = meas.strokeWidth
                    style = Paint.Style.STROKE
                    isAntiAlias = true
                }
                val mTextPaint = Paint().apply {
                    color = meas.colorHex.toInt()
                    textSize = 10f
                    typeface = Typeface.create(Typeface.DEFAULT, Typeface.BOLD)
                    isAntiAlias = true
                }

                if (meas.type == MeasurementType.DISTANCE_LINE && meas.points.size >= 2) {
                    val p1 = meas.points[0]
                    val p2 = meas.points[1]
                    canvas.drawLine(p1.x, p1.y, p2.x, p2.y, mPaint)
                    // Ticks
                    canvas.drawLine(p1.x - 5, p1.y - 5, p1.x + 5, p1.y + 5, mPaint)
                    canvas.drawLine(p2.x - 5, p2.y - 5, p2.x + 5, p2.y + 5, mPaint)
                    val dx = p2.x - p1.x
                    val dy = p2.y - p1.y
                    val distPx = Math.hypot(dx.toDouble(), dy.toDouble()).toFloat()
                    val label = meas.scale.format(distPx)
                    canvas.drawText(label, (p1.x + p2.x) / 2, (p1.y + p2.y) / 2 - 6, mTextPaint)
                }
            }

            // 7. Draw Form Fields
            val pageFields = formFields.filter { it.pageIndex == pageIndex }
            for (field in pageFields) {
                val fPaint = Paint().apply {
                    color = Color.rgb(220, 230, 245)
                    style = Paint.Style.FILL
                }
                val fBorder = Paint().apply {
                    color = Color.rgb(100, 130, 180)
                    style = Paint.Style.STROKE
                    strokeWidth = 1f
                }
                canvas.drawRect(field.x, field.y, field.x + field.width, field.y + field.height, fPaint)
                canvas.drawRect(field.x, field.y, field.x + field.width, field.y + field.height, fBorder)
                canvas.drawText("${field.label}: ${field.value}", field.x + 4f, field.y + field.height - 8f, textPaint)
            }

            pdfDocument.finishPage(page)
        }

        // Save PDF file to cache directory
        val cleanName = documentTitle.replace("[^a-zA-Z0-9_-]".toRegex(), "_")
        val outputFile = File(context.cacheDir, "${cleanName}_export_${System.currentTimeMillis()}.pdf")
        FileOutputStream(outputFile).use { out ->
            pdfDocument.writeTo(out)
        }
        pdfDocument.close()
        return outputFile
    }
}
